    print("ARIA · Artroom 369 (escribe 'salir' para terminar)")
    while True:
        texto = input("Tú: ").strip()
        if not texto:
            continue
        intencion, _, respuesta = bot.responder(texto)
        print("ARIA:", respuesta)
        if intencion == "despedida":
            break

